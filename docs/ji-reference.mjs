export function figure4Reference(c){
 const result={};
 for(const [key,p] of Object.entries(profiles)){
  const rows=p.witness.map(([id,s,v,sa,sd,aa,ad])=>{
   const outbound=id[0]==='E',start=Math.max(sa,aa);
   return {id,direction:outbound?'export':'import',smv:'SMV-'+s,agv:'AGV-'+v,lane:outbound?'L2-1':'L1-1',smvArrival:sa,smvDeparture:sd,agvArrival:aa,agvDeparture:ad,start,end:start+c.T0};
  });
  result[key]={label:p.label,cmax:p.cmax,waiting:p.waiting,rows};
 }
 return result;
}
